func TestNATRulesMasqueradeRedirectDNSAndKeepSandboxesApart(t *testing.T) {
	t.Parallel()

	rules := natRules("opsb0", netip.MustParsePrefix("10.237.0.0/24"), netip.MustParseAddr("10.237.0.1"), 1053)

	for _, want := range []string{
		// Replaced whole on every start, never appended to.
		"table ip openplan_sandbox\ndelete table ip openplan_sandbox\n",
		`ip saddr 10.237.0.0/24 oifname != "opsb0" masquerade`,
		`iifname "opsb0" ip daddr 10.237.0.1 meta l4proto { tcp, udp } th dport 53 redirect to :1053`,
		`iifname "opsb0" oifname "opsb0" drop`,
	} {
		if !strings.Contains(rules, want) {
			t.Fatalf("rules lack %q:\n%s", want, rules)
		}
	}
}

func TestSandboxResolvConfPointsAtTheGateway(t *testing.T) {
	t.Parallel()

	executor := []byte("# Generated by Docker\nnameserver 127.0.0.11\nsearch svc.cluster.local cluster.local\noptions ndots:0\n")
	got := string(sandboxResolvConf(executor, netip.MustParseAddr("10.237.0.1")))
	want := "nameserver 10.237.0.1\nsearch svc.cluster.local cluster.local\noptions ndots:0\n"
	if got != want {
		t.Fatalf("resolv.conf = %q, want %q", got, want)
	}
}

func TestResolversReadsTheExecutorsNameservers(t *testing.T) {
	t.Parallel()

	got := resolvers([]byte("nameserver 127.0.0.11\nnameserver fd00::1\nsearch x\n"))
	if want := []string{"127.0.0.11:53", "[fd00::1]:53"}; !slices.Equal(got, want) {
		t.Fatalf("resolvers = %q, want %q", got, want)
	}
}

func TestAddressPoolHandsOutEachHostOnce(t *testing.T) {
	t.Parallel()

	// A /29: .0 is the network, .1 the gateway, .7 broadcast; .2 to .6 are
	// the sandboxes'.
	pool := newAddressPool(netip.MustParsePrefix("10.237.0.0/29"))
	var taken []netip.Addr
	for range 5 {
		addr, err := pool.take()
		if err != nil {
			t.Fatal(err)
		}
		taken = append(taken, addr)
	}
	want := []netip.Addr{
		netip.MustParseAddr("10.237.0.2"), netip.MustParseAddr("10.237.0.3"), netip.MustParseAddr("10.237.0.4"),
		netip.MustParseAddr("10.237.0.5"), netip.MustParseAddr("10.237.0.6"),
	}
	if !slices.Equal(taken, want) {
		t.Fatalf("taken = %v, want %v", taken, want)
	}
	if _, err := pool.take(); err == nil {
		t.Fatal("took a sixth address from a /29")
	}
	pool.give(netip.MustParseAddr("10.237.0.4"))
	if addr, err := pool.take(); err != nil || addr != netip.MustParseAddr("10.237.0.4") {
		t.Fatalf("after give: %v, %v; want 10.237.0.4 again", addr, err)
	}
}

func TestHostLinkNamesFitAndDiffer(t *testing.T) {
	t.Parallel()

	a, b := hostLinkName("openplan-0123456789abcdef01234567"), hostLinkName("openplan-0123456789abffffffffffff")
	// Linux caps interface names at 15 bytes.
	if len(a) > 15 || a == b {
		t.Fatalf("names %q and %q: want distinct and at most 15 bytes", a, b)
	}
}

func TestOCISpecJoinsTheSandboxsNetworkNamespace(t *testing.T) {
	t.Parallel()

	spec := ociSpec(testJob(), "/guest", nil, "/sandboxes/x", Limits{MemoryMiB: 1, CPUs: 1, Pids: 1},
		sandboxNetwork{Namespace: "/state/netns/x", ResolvConf: "/state/resolv.conf"})

	var joined bool
	for _, ns := range spec.Linux.Namespaces {
		if ns.Type == "network" {
			joined = ns.Path == "/state/netns/x"
		}
	}
	if !joined {
		t.Fatalf("namespaces = %+v, want the sandbox's network namespace by path", spec.Linux.Namespaces)
	}
	var mounted bool
	for _, m := range spec.Mounts {
		if m.Destination == "/etc/resolv.conf" {
			mounted = m.Source == "/state/resolv.conf" && slices.Contains(m.Options, "ro")
		}
	}
	if !mounted {
		t.Fatalf("mounts = %+v, want resolv.conf read-only", spec.Mounts)
	}
}

// A failed attach undoes itself, its address included: one that kept the
// address would leave the subnet a sandbox short after every failure, until
// no sandbox could start.
func TestAFailedAttachGivesItsAddressBack(t *testing.T) {
	t.Parallel()

	subnet := netip.MustParsePrefix("10.237.0.0/29")
	// No directory to pin the namespace in: attach fails before it needs a
	// privilege.
	n := &Network{subnet: subnet, namespaces: filepath.Join(t.TempDir(), "missing"), pool: newAddressPool(subnet)}
	if _, err := n.attach("openplan-0123456789abcdef01234567"); err == nil {
		t.Fatal("attach succeeded with nowhere to pin the namespace")
	}
	if len(n.pool.used) != 0 {
		t.Fatalf("addresses taken after a failed attach: %v, want none", n.pool.used)
	}
}
